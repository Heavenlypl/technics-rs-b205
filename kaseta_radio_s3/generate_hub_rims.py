"""4x supersampling for the fixed light hub ring at radii 18 and 19."""
from pathlib import Path
Z=100.4/84.3*480/312
rows=[];weights=[]
for y in range(244):
 dy=(y+38+.5-160)/Z+1;spans=[]
 for part,cx in enumerate((88,232)):
  run=[]
  for x in range(part*240,(part+1)*240):
   dx=(x+.5-240)/Z+160-cx
   if 17.5**2<=dx*dx+dy*dy<=19.5**2:
    c=[0,0,0]
    for sy in range(4):
     for sx in range(4):
      xx=dx+((sx+.5)/4-.5)/Z;yy=dy+((sy+.5)/4-.5)/Z;d2=xx*xx+yy*yy
      c[0 if d2<=18**2 else 1 if d2<=19**2 else 2]+=1
    if run and x!=run[-1][0]+1:
     spans.append((run[0][0],run[-1][0],len(weights)));weights.extend(v for _,v in run);run=[]
    run.append((x,sum(v<<(i*5) for i,v in enumerate(c))))
  if run:spans.append((run[0][0],run[-1][0],len(weights)));weights.extend(v for _,v in run)
 assert len(spans)<=4
 rows.append(spans+[(-1,-1,0)]*(4-len(spans)))
out=['// Generated by generate_hub_rims.py: fixed hub ring, 4x SSAA.','#pragma once','#include <Arduino.h>','struct HubSpan {int16_t left,right;uint16_t offset;};','static const HubSpan HUB_SPANS[244][4] PROGMEM = {']
out += [' {'+','.join('{%d,%d,%d}'%v for v in spans)+'},' for spans in rows]
out += ['};',f'static const uint16_t HUB_WEIGHTS[{len(weights)}] PROGMEM = {{']
for i in range(0,len(weights),20):out.append(' '+','.join(f'0x{v:04x}' for v in weights[i:i+20])+',')
out+=['};'];Path(__file__).with_name('hub_coverage.h').write_text('\n'.join(out)+'\n')
print(f'Hub AA: {len(weights)} pixels, {len(weights)*2+244*24} bytes flash')
