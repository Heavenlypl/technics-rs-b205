"""Stałe pokrycia pikseli obwodów szpul: supersampling 4x, bez RAM na klatki."""
from pathlib import Path

W,H=480,244
ZOOM=100.4/84.3*480/312
weights=[]
rows=[]
for row in range(H):
    y=(row+38+.5-160)/ZOOM+121-120
    spans=[]
    for part,cx in enumerate((88,232)):
        run=[]
        for x in range(part*240,(part+1)*240):
            dx=(x+.5-240)/ZOOM+160-cx
            if 63.5**2 <= dx*dx+y*y <= 67.5**2:
                counts=[0,0,0,0,0]
                for sy in range(4):
                    for sx in range(4):
                        xx=dx+((sx+.5)/4-.5)/ZOOM
                        yy=y+((sy+.5)/4-.5)/ZOOM
                        d2=xx*xx+yy*yy
                        band=0 if d2<=64**2 else 1 if d2<=65**2 else 2 if d2<=66**2 else 3 if d2<=67**2 else 4
                        counts[band]+=1
                packed=sum(v<<(i*5) for i,v in enumerate(counts))
                if run and x!=run[-1][0]+1:
                    spans.append((run[0][0],run[-1][0],len(weights)))
                    weights.extend(v for _,v in run)
                    run=[]
                run.append((x,packed))
        if run:
            spans.append((run[0][0],run[-1][0],len(weights)))
            weights.extend(v for _,v in run)
    assert len(spans)<=4
    rows.append(spans+[(-1,-1,0)]*(4-len(spans)))
assert len(weights)<65536
out=['// Generated by generate_rims.py: 4x SSAA coverage, fixed outer circles.',
     '#pragma once','#include <Arduino.h>',
     'struct RimSpan { int16_t left, right; uint16_t offset; };',
     'static const RimSpan RIM_SPANS[244][4] PROGMEM = {']
out += ['  {'+','.join('{%d,%d,%d}'%s for s in spans)+'},' for spans in rows]
out+=['};',f'static const uint32_t RIM_WEIGHTS[{len(weights)}] PROGMEM = {{']
for i in range(0,len(weights),12): out.append('  '+','.join(f'0x{v:08x}' for v in weights[i:i+12])+',')
out+=['};']
Path(__file__).with_name('rim_coverage.h').write_text('\n'.join(out)+'\n')
print(f'Obwody: {len(weights)} pikseli, {len(weights)*4+244*4*6} bajtów flash, bez bufora RAM.')
