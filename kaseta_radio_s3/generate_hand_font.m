// Process-local CoreText atlas: Bradley Hand, hand-printed capitals with Polish letters.
#import <Foundation/Foundation.h>
#import <CoreText/CoreText.h>
#import <CoreGraphics/CoreGraphics.h>

int main(int argc,char **argv) {
 @autoreleasepool {
  if(argc!=2) return 2;
  const int scale=4;
  CTFontRef font=CTFontCreateWithName(CFSTR("BradleyHandITCTT-Bold"),26*scale,NULL);
  NSLog(@"Actual font: %@",(__bridge NSString *)CTFontCopyPostScriptName(font));
  CGColorSpaceRef gray=CGColorSpaceCreateDeviceGray();
  CGFloat components[]={1,1};CGColorRef white=CGColorCreate(gray,components);
  NSDictionary *attrs=@{(__bridge NSString*)kCTFontAttributeName:(__bridge id)font,
   (__bridge NSString*)kCTForegroundColorAttributeName:(__bridge id)white};
  NSMutableArray<NSNumber*> *codes=[NSMutableArray array];
  for(int i=32;i<=126;i++) if(i<97||i>122) [codes addObject:@(i)];
  NSString *polish=@"ĄĆĘŁŃÓŚŹŻ";
  for(NSUInteger i=0;i<polish.length;i++) [codes addObject:@([polish characterAtIndex:i])];
  [codes sortUsingSelector:@selector(compare:)];
  NSMutableData *all=[NSMutableData data];
  NSMutableString *glyphs=[NSMutableString string];
  for(NSNumber *number in codes) {
   unichar code=number.unsignedShortValue;
   NSString *text=[NSString stringWithCharacters:&code length:1];
   NSAttributedString *at=[[NSAttributedString alloc] initWithString:text attributes:attrs];
   CTLineRef line=CTLineCreateWithAttributedString((__bridge CFAttributedStringRef)at);
   double advance=CTLineGetTypographicBounds(line,NULL,NULL,NULL)/scale;
   int xoff=0,yoff=0,w=0,h=0;
   NSUInteger offset=all.length;
   CGRect bounds=CTLineGetImageBounds(line,NULL);
   if(!CGRectIsNull(bounds) && bounds.size.width>0 && bounds.size.height>0) {
    int x0=floor(bounds.origin.x/scale)-1,y0=floor(bounds.origin.y/scale)-1;
    int x1=ceil(CGRectGetMaxX(bounds)/scale)+1,y1=ceil(CGRectGetMaxY(bounds)/scale)+1;
    int ow=x1-x0,oh=y1-y0,W=ow*scale,H=oh*scale;
    uint8_t *high=calloc(W*H,1), *alpha=calloc(ow*oh,1);
    CGContextRef ctx=CGBitmapContextCreate(high,W,H,8,W,gray,kCGImageAlphaNone);
    CGContextSetShouldAntialias(ctx,true);CGContextSetAllowsAntialiasing(ctx,true);
    CGContextSetShouldSmoothFonts(ctx,false);CGContextSetTextMatrix(ctx,CGAffineTransformIdentity);
    CGContextSetTextPosition(ctx,-x0*scale,-y0*scale);CTLineDraw(line,ctx);
    int minx=ow,miny=oh,maxx=-1,maxy=-1;
    for(int y=0;y<oh;y++) for(int x=0;x<ow;x++) {
     int sum=0;
     for(int sy=0;sy<scale;sy++) for(int sx=0;sx<scale;sx++) sum+=high[(y*scale+sy)*W+x*scale+sx];
     uint8_t a=(sum*15+2040)/(255*scale*scale);alpha[y*ow+x]=a;
     if(a) {minx=MIN(minx,x);maxx=MAX(maxx,x);miny=MIN(miny,y);maxy=MAX(maxy,y);}
    }
    if(maxx>=minx) {
     xoff=x0+minx;yoff=-y1+miny;w=maxx-minx+1;h=maxy-miny+1;
     uint8_t pair=0;int count=0;
     for(int y=miny;y<=maxy;y++) for(int x=minx;x<=maxx;x++) {
      pair|=alpha[y*ow+x]<<((count&1)*4);count++;
      if(!(count&1)) {[all appendBytes:&pair length:1];pair=0;}
     }
     if(count&1) [all appendBytes:&pair length:1];
    }
    CGContextRelease(ctx);free(high);free(alpha);
   }
   [glyphs appendFormat:@"  {%u,%lu,%d,%d,%d,%d,%d},\n",code,(unsigned long)offset,(int)lround(advance*64),xoff,yoff,w,h];
   CFRelease(line);
  }
  if(all.length>65535) return 3;
  NSMutableString *out=[NSMutableString stringWithString:@"// Generated by generate_hand_font.m: Bradley Hand Bold 26, separate hand-printed capitals, SSAA 4x, 4-bit alpha.\n#pragma once\n#include <stdint.h>\n#ifdef ARDUINO\n#include <Arduino.h>\n#else\n#define PROGMEM\n#define pgm_read_byte(p) (*(const uint8_t *)(p))\n#endif\nstruct HandStationGlyph { uint16_t code, offset, advance64; int8_t xOffset,yOffset; uint8_t width,height; };\n"];
  [out appendFormat:@"static const unsigned HAND_STATION_GLYPH_COUNT=%lu;\nstatic const HandStationGlyph HAND_STATION_GLYPHS[] PROGMEM = {\n%@};\n",(unsigned long)codes.count,glyphs];
  [out appendFormat:@"static const uint8_t HAND_STATION_FONT_ALPHA[%lu] PROGMEM = {\n",(unsigned long)all.length];
  const uint8_t *bytes=all.bytes;
  for(NSUInteger i=0;i<all.length;i++) {
   if(i%24==0) [out appendString:@"  "];
   [out appendFormat:@"0x%02x,",bytes[i]];
   if(i%24==23 || i+1==all.length) [out appendString:@"\n"];
  }
  [out appendString:@"};\n"];
  NSString *dir=[NSString stringWithUTF8String:argv[1]];
  if(![out writeToFile:[dir stringByAppendingPathComponent:@"hand_station_font.h"] atomically:YES encoding:NSUTF8StringEncoding error:nil]) return 4;
  printf("Font: %lu znaków, %lu bajtów bitmap, polskie znaki w UTF-8.\n",(unsigned long)codes.count,(unsigned long)all.length);
  CFRelease(font);CGColorRelease(white);CGColorSpaceRelease(gray);
  return 0;
 }
}
